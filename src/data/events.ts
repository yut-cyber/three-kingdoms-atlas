const CITY_INDEX = new Map(CITIES.map((c) => [c.name, c.at]));

export function eventCoord(e: HistoricalEvent): LonLat {
  return CITY_INDEX.get(e.city) ?? [112.45, 34.62];
}

export function eventRoute(e: HistoricalEvent): LonLat[] | undefined {
  if (!e.route) return undefined;
  const pts = e.route.map((name) => CITY_INDEX.get(name)).filter((p): p is LonLat => !!p);
  return pts.length > 1 ? pts : undefined;
}
