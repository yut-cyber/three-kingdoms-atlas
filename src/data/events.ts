  place: string;
  factions: EventFaction[];
  importance: 1 | 2 | 3;
  figures: string[];
  summary: string;
  result: string;
  /** 进攻方（史书所载出兵一方） */
  attacker?: string;
  /** 防守方 */
  defender?: string;
  /** 行军路线（城池名序列） */
